package uo.ri.cws.application.service.paymentmean.voucher.commands;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import uo.ri.conf.Factories;
import uo.ri.cws.application.persistence.client.ClientGateway;
import uo.ri.cws.application.persistence.client.ClientGateway.ClientRecord;
import uo.ri.cws.application.persistence.paymentmean.PaymentMeanGateway;
import uo.ri.cws.application.persistence.util.command.Command;
import uo.ri.cws.application.persistence.voucher.VoucherGateway;
import uo.ri.cws.application.persistence.voucher.VoucherGateway.VoucherRecord;
import uo.ri.cws.application.persistence.workorder.WorkOrderGateway;
import uo.ri.cws.application.persistence.workorder.WorkOrderGateway.WorkOrderRecord;
import uo.ri.util.exception.BusinessException;

/**
 * Generates the vouchers the clients are entitled to. Only the policy of 20
 * euro vouchers for every three paid work orders is implemented.
 */
public class GenerateVouchers implements Command<int[]> {

    private static final int WORK_ORDERS_PER_VOUCHER = 3;
    private static final BigDecimal WORK_ORDERS_VOUCHER_AMOUNT = new BigDecimal("20.00");
    private static final String WORK_ORDERS_VOUCHER_DESCRIPTION = "Por tres órdenes de trabajo";

    private final ClientGateway cg = Factories.persistence.forClient();
    private final WorkOrderGateway wg = Factories.persistence.forWorkOrder();
    private final PaymentMeanGateway pmg = Factories.persistence.forPaymentMean();
    private final VoucherGateway vg = Factories.persistence.forVoucher();

    @Override
    public int[] execute() throws BusinessException {
        int workOrderVouchers = 0;
        for (ClientRecord client : cg.findAll()) {
            workOrderVouchers += generateWorkOrderVouchersFor(client.id);
        }
        // in order: 20, 25 and 30 euro vouchers
        return new int[] { workOrderVouchers, 0, 0 };
    }

    /*
     * One voucher for every three work orders whose invoice is paid and that
     * have not been used yet for another voucher. Returns how many vouchers
     * have been generated.
     */
    private int generateWorkOrderVouchersFor(String clientId) {
        List<WorkOrderRecord> available = findNotUsedPaidWorkOrders(clientId);
        int vouchers = available.size() / WORK_ORDERS_PER_VOUCHER;

        markAsUsed(available, vouchers * WORK_ORDERS_PER_VOUCHER);
        for (int i = 0; i < vouchers; i++) {
            addVoucher(clientId, WORK_ORDERS_VOUCHER_AMOUNT, WORK_ORDERS_VOUCHER_DESCRIPTION);
        }
        return vouchers;
    }

    private List<WorkOrderRecord> findNotUsedPaidWorkOrders(String clientId) {
        List<WorkOrderRecord> res = new ArrayList<>();
        for (WorkOrderRecord w : wg.findByClientIdAndInvoiceState(clientId, "PAID")) {
            if (!w.usedforvoucher) {
                res.add(w);
            }
        }
        return res;
    }

    private void markAsUsed(List<WorkOrderRecord> workOrders, int howMany) {
        LocalDateTime now = LocalDateTime.now();
        for (int i = 0; i < howMany; i++) {
            WorkOrderRecord w = workOrders.get(i);
            w.usedforvoucher = true;
            w.version++;
            w.updatedAt = now;
            wg.update(w);
        }
    }

    /*
     * A voucher is stored in TPaymentMeans and in TVouchers; the row in
     * TPaymentMeans goes first, as TVouchers references it. Its code is
     * generated by the system.
     */
    private void addVoucher(String clientId, BigDecimal amount, String description) {
        VoucherRecord v = new VoucherRecord();
        v.dtype = "Voucher";
        v.accumulated = BigDecimal.ZERO;
        v.client_id = clientId;
        v.code = UUID.randomUUID().toString();
        v.description = description;
        v.available = amount;
        pmg.add(v);
        vg.add(v);
    }
}
